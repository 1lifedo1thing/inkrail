extension Bundle {
    static let module = Bundle(url: URL(fileURLWithPath: CommandLine.arguments[1])
        .appendingPathComponent("FixtureResources.bundle"))!
}

private struct StyleCheckFailure: Error, CustomStringConvertible {
    let description: String
}

@MainActor
private struct StyleGallery: View {
    var body: some View {
        VStack(alignment: .leading, spacing: 20) {
            Text("A little machine. Twelve ways to make it yours.")
                .font(.custom("Courier", size: 21)).foregroundColor(DeskPalette.ink)
            Text("Original Inkrail materials · Actual production capsule and rail")
                .font(.system(size: 12)).foregroundColor(DeskPalette.mutedInk)
            LazyVGrid(columns: Array(repeating: GridItem(.fixed(240), spacing: 16), count: 3), spacing: 16) {
                ForEach(MechanismStyle.allCases, id: \.self) { style in
                    VStack(spacing: 8) {
                        ZStack {
                            RailView(finish: style.material.preferredRail, style: style).frame(width: 210)
                            CapsuleView(finish: .porcelain, style: style)
                        }.frame(height: 100)
                        Text(style.label).font(.custom("Courier", size: 14))
                        Text(style.subtitle).font(.system(size: 10)).foregroundColor(DeskPalette.mutedInk)
                    }
                    .padding(.vertical, 15).frame(width: 240)
                    .background(RoundedRectangle(cornerRadius: 12).fill(.white.opacity(0.34)))
                    .overlay(RoundedRectangle(cornerRadius: 12).stroke(DeskPalette.ink.opacity(0.1), lineWidth: 0.6))
                }
            }
        }.padding(24).background(DeskPalette.paper)
    }
}

@main
@MainActor
private enum MachineStyleCheck {
    static let output = URL(fileURLWithPath: CommandLine.arguments[1])
    static var groups = 0

    static func require(_ condition: @autoclosure () -> Bool, _ detail: String) throws {
        guard condition() else { throw StyleCheckFailure(description: detail) }
    }

    static func passed(_ label: String) {
        groups += 1
        print("PASS: \(label)")
    }

    static func main() throws {
        try checkModel()
        try checkEmitterAndDeterminism()
        _ = try render(StyleGallery(), name: "twelve-style-gallery")
        var preview = WritingPreferences()
        preview.mechanismStyle = .wildflower
        _ = try render(MechanismStylePicker(preferences: .constant(preview))
            .padding(20).frame(width: 620).background(DeskPalette.paper), name: "production-style-picker")
        let lamps = VStack(spacing: 12) {
            ForEach(Array(MechanismStyle.allCases.suffix(6)), id: \.self) { style in
                HStack(spacing: 12) {
                    ForEach([0.0, 1.0], id: \.self) { warmth in
                        NightLampPreview(preferences: preferences(style, warmth: warmth)).frame(width: 340)
                    }
                }
            }
        }.padding(12).background(DeskPalette.background)
        _ = try render(lamps, name: "new-style-lamp-endpoints")
        print("Passed \(groups) machine-style check groups; rendered all 12 styles, picker and new-style lamp endpoints.")
        print("These are component renders and direct model checks, not running-app UI or XCTest results.")
    }

    static func checkModel() throws {
        let original = ["classic", "brushedSteel", "champagne", "walnut", "porcelain", "midnight"]
        try require(MechanismStyle.allCases.count == 12, "Expected twelve choices")
        try require(Array(MechanismStyle.allCases.prefix(6)).map(\.rawValue) == original,
                    "An existing identifier or its ordering changed")
        try require(Set(MechanismStyle.allCases.map(\.rawValue)).count == 12
                    && Set(MechanismStyle.allCases.map(\.label)).count == 12,
                    "Style labels or identifiers collide")
        try require(MechanismMaterial.housingWidth == 110 && MechanismMaterial.housingHeight == 46,
                    "Housing footprint changed")
        passed("All six existing styles remain first; twelve unique choices retain the 110 × 46 footprint")

        // A literal pre-expansion record, not generated by this version's encoder.
        let legacy = """
        {"mechanismStyle":"midnight","matchRailToStyle":false,"capsule":"cobalt",
         "rail":"brass","paper":"cream","paperStartPosition":"bottom",
         "paperMotion":"roll","writingFont":"georgia","typewriterSound":"soft",
         "lampWarmth":0.27,"lampIntensity":0.64}
        """
        let decoder = JSONDecoder()
        let old = try decoder.decode(WritingPreferences.self, from: Data(legacy.utf8))
        try require(old.mechanismStyle == .midnight && !old.matchRailToStyle
                    && old.capsule == .cobalt && old.effectiveRailFinish == .brass
                    && old.paper == .cream && old.paperStartPosition == .bottom
                    && old.paperMotion == .roll && old.writingFont == .georgia
                    && old.typewriterSound == .soft && old.lampWarmth == 0.27
                    && old.lampIntensity == 0.64, "Literal legacy preferences changed")
        let defaults = try decoder.decode(WritingPreferences.self, from: Data("{}".utf8))
        let future = try decoder.decode(WritingPreferences.self, from: Data(
            "{\"mechanismStyle\":\"future\",\"rail\":\"brass\",\"lampWarmth\":0.31}".utf8))
        try require(defaults.mechanismStyle == .walnut && defaults.matchRailToStyle && defaults.effectiveRailFinish == .brass
                    && future.mechanismStyle == .walnut
                    && future.rail == .brass && future.lampWarmth == 0.31, "Fallback resets preferences")
        passed("Literal legacy values survive, and missing or unknown styles fall back to Walnut")

        for style in MechanismStyle.allCases {
            let material = style.material
            try require(material.bodyColors.count >= 3
                        && (material.bodyColors + [material.trim]).allSatisfy { $0 <= 0xFFFFFF }
                        && (0...23).contains(material.cornerRadius), "Invalid material tokens: \(style)")
            for match in [true, false] {
                for rail in RailFinish.allCases {
                    var p = old
                    p.mechanismStyle = style
                    p.matchRailToStyle = match
                    p.rail = rail
                    let data = try JSONEncoder().encode(p)
                    let decoded = try decoder.decode(WritingPreferences.self, from: data)
                    try require(decoded == p, "Style/rail combination did not persist: \(style)")
                    let expected = style != .classic && match ? material.preferredRail : rail
                    try require(p.effectiveRailFinish == expected && p.rail == rail
                                && p.capsule == old.capsule && p.lampWarmth == old.lampWarmth,
                                "Style changed independent Classic colour, manual rail or lamp: \(style)")
                }
            }
        }
        passed("All 72 style/rail combinations persist and retain independent Classic and lamp choices")
    }

    static func preferences(_ style: MechanismStyle, warmth: Double) -> WritingPreferences {
        var p = WritingPreferences()
        p.mechanismStyle = style
        p.nightMode = true
        p.lampWarmth = warmth
        p.lampIntensity = 0.82
        return p
    }

    static func checkEmitterAndDeterminism() throws {
        for style in MechanismStyle.allCases {
            let cool = try render(CapsuleView(finish: .porcelain, style: style,
                                              lampOn: true, lampWarmth: 0), name: "\(style.rawValue)-cool")
            let warm = try render(CapsuleView(finish: .porcelain, style: style,
                                              lampOn: true, lampWarmth: 1), name: "\(style.rawValue)-warm")
            let a = NSBitmapImageRep(cgImage: cool)
            let b = NSBitmapImageRep(cgImage: warm)
            // CapsuleView's fixed emitter centre, at 2× render scale.
            guard let cold = a.colorAt(x: 116, y: 56)?.usingColorSpace(.deviceRGB),
                  let hot = b.colorAt(x: 116, y: 56)?.usingColorSpace(.deviceRGB) else {
                throw StyleCheckFailure(description: "Could not sample \(style) emitter")
            }
            try require(cold.blueComponent - hot.blueComponent > 0.15
                        && cold.greenComponent - hot.greenComponent > 0.05,
                        "\(style) emitter shifted or lost the shared warmth mapping")
        }
        passed("All twelve emitters retain the same anchor and cool-to-amber warmth range")
        for style in MechanismStyle.allCases.suffix(6) {
            let first = try render(StyledCapsuleHousing(style: style, lampOn: false), name: "\(style.rawValue)-housing")
            let second = try render(StyledCapsuleHousing(style: style, lampOn: false), name: "\(style.rawValue)-repeat")
            try require(first.width == 220 && first.height == 92, "\(style) changed its housing dimensions")
            let a = NSBitmapImageRep(cgImage: first)
            let b = NSBitmapImageRep(cgImage: second)
            for y in stride(from: 0, to: first.height, by: 2) {
                for x in stride(from: 0, to: first.width, by: 2) {
                    guard let lhs = a.colorAt(x: x, y: y)?.usingColorSpace(.deviceRGB),
                          let rhs = b.colorAt(x: x, y: y)?.usingColorSpace(.deviceRGB) else { continue }
                    guard lhs.alphaComponent > 0.99, rhs.alphaComponent > 0.99 else { continue }
                    try require(abs(lhs.redComponent - rhs.redComponent) < 0.012
                                && abs(lhs.greenComponent - rhs.greenComponent) < 0.012
                                && abs(lhs.blueComponent - rhs.blueComponent) < 0.012,
                                "\(style) texture changed between identical renders")
                }
            }
        }
        passed("All six new housings render at the original dimensions with deterministic textures")
    }

    static func render<V: View>(_ view: V, name: String) throws -> CGImage {
        let renderer = ImageRenderer(content: view)
        renderer.scale = 2
        guard let image = renderer.cgImage,
              let png = NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:]) else {
            throw StyleCheckFailure(description: "Could not render \(name)")
        }
        try png.write(to: output.appendingPathComponent(name + ".png"))
        return image
    }
}
